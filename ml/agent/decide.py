"""CityPulse insight agent powered by Gemini function calling."""

from __future__ import annotations

import argparse
from dataclasses import asdict
from datetime import date
import json
import os
from pathlib import Path
import subprocess
import sys
import time
from typing import Any

ROOT = Path(__file__).resolve().parents[2]


def _safe_workspace_path(relative_path: str) -> Path:
    """Resolve a report path while preventing reads outside the repository."""
    candidate = (ROOT / relative_path).resolve()
    if candidate != ROOT and ROOT not in candidate.parents:
        raise ValueError("report path must stay inside the CityPulse repository")
    return candidate


def read_json_report(path: str) -> dict[str, Any]:
    """Read a JSON report generated by a CityPulse signal."""
    report_path = _safe_workspace_path(path)
    if report_path.suffix.lower() != ".json":
        raise ValueError("only JSON reports can be read by the insight agent")
    try:
        with report_path.open(encoding="utf-8") as report_file:
            payload = json.load(report_file)
    except FileNotFoundError as error:
        raise FileNotFoundError(f"Report does not exist: {path}") from error
    if not isinstance(payload, dict):
        raise ValueError(f"Report must contain a JSON object: {path}")
    return payload


def get_local_context(city: str, days: int = 7) -> dict[str, Any]:
    """Read city metadata, upcoming demo events, holidays, and namedays."""
    if not city.strip():
        raise ValueError("city must not be empty")
    if not 1 <= days <= 16:
        raise ValueError("days must be between 1 and 16")

    with (ROOT / "data" / "ro_cities.json").open(encoding="utf-8") as file:
        cities = json.load(file)
    selected_city = next(
        (
            item
            for item in cities
            if str(item.get("name", "")).casefold() == city.strip().casefold()
        ),
        None,
    )
    if selected_city is None:
        available = ", ".join(item["name"] for item in cities)
        raise ValueError(f"Unknown city {city!r}. Choose one of: {available}")

    with (ROOT / "data" / "ro_events.json").open(encoding="utf-8") as file:
        event_payload = json.load(file)
    with (ROOT / "data" / "ro_holidays_namedays.json").open(encoding="utf-8") as file:
        calendar = json.load(file)

    today = date.today()
    end = today.fromordinal(today.toordinal() + days - 1)
    events = [
        event
        for event in event_payload["events"]
        if event["city"].casefold() == selected_city["name"].casefold()
        and event["start_date"] <= end.isoformat()
        and event["end_date"] >= today.isoformat()
    ]
    holidays = [
        holiday
        for holiday in calendar["holidays"]
        if today.isoformat() <= holiday["date"] <= end.isoformat()
    ]
    namedays = [
        nameday
        for nameday in calendar["namedays"]
        if today.isoformat() <= nameday["date"] <= end.isoformat()
    ]
    return {
        "city": selected_city,
        "window": {"start": today.isoformat(), "end": end.isoformat()},
        "events": events,
        "holidays": holidays,
        "namedays": namedays,
        "data_status": "curated demo data; verify before production use",
    }


def get_weather(city: str, days: int = 5) -> dict[str, Any]:
    """Fetch weather through the existing Open-Meteo integration."""
    root_string = str(ROOT)
    if root_string not in sys.path:
        sys.path.insert(0, root_string)
    from ml.signals.open_meteo import fetch_weather

    result = asdict(fetch_weather(city, days=days))
    result["forecast"] = [
        {**forecast_day, "day": forecast_day["day"].isoformat()}
        for forecast_day in result["forecast"]
    ]
    return result


def run_trend_forecast(
    keywords: list[str],
    city: str,
    timeframe: str = "today 3-m",
) -> dict[str, Any]:
    """Run the approved trend command and return its generated JSON."""
    if not 1 <= len(keywords) <= 3:
        raise ValueError("provide between 1 and 3 keywords")
    output_path = ROOT / "trend_agent_forecast.json"
    command = [
        sys.executable,
        str(ROOT / "ml" / "signals" / "simulated_trends.py"),
        *keywords,
        "--city",
        city,
        "--timeframe",
        timeframe,
        "--output",
        str(output_path),
    ]
    result = subprocess.run(
        command,
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or "trend forecast command failed")
    return read_json_report("trend_agent_forecast.json")


def ask_agent(question: str, report_path: str | None = None) -> str:
    """Ask the agent for a marketing decision using controlled tools."""
    try:
        from google import genai
        from google.genai import errors
        from google.genai import types
    except ImportError as error:
        raise RuntimeError(
            "google-genai is required; install dependencies with "
            "`python -m pip install -r requirements.txt`"
        ) from error

    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise RuntimeError(
            "GEMINI_API_KEY is missing. Set it in PowerShell with "
            "$env:GEMINI_API_KEY='your-key'"
        )
    client = genai.Client(api_key=api_key)
    context = (
        f"Start by reading this report: {report_path}. " if report_path else ""
    )
    instructions = (
        "You are the CityPulse marketing insight agent. "
        "Use tools whenever evidence is needed; never invent weather or trend values. "
        "For any question involving search demand, trends, peaks, or posting dates, "
        "you MUST call run_trend_forecast before deciding. Extract one to three "
        "product keywords and the city from the user's request. "
        "For any question involving weather, rain, temperature, or local conditions, "
        "you MUST call get_weather before deciding. "
        "If the user asks for both, call both tools. "
        "You may call read_json_report only when a report path is explicitly provided. "
        "For any local context, events, holidays, namedays, or city question, you MUST "
        "call get_local_context. Use its results in the recommendation. "
        "Decide whether the current ad should stay, receive a light touch, or be "
        "replaced. Recommend a specific posting date when the data supports one. "
        "Return concise JSON with keys: decision (GENERATE, LIGHT_TOUCH, or SKIP), "
        "should_change_ad (boolean), recommended_day (ISO date or null), "
        "confidence (0 to 1), reasons (array of strings), evidence (array of objects), "
        "and limitations (array of strings). "
        + context
    )
    config = types.GenerateContentConfig(
        system_instruction=instructions,
        tools=[
            read_json_report,
            get_local_context,
            get_weather,
            run_trend_forecast,
        ],
        response_mime_type="application/json",
    )
    models = [
        os.getenv("GEMINI_MODEL", "gemini-3.8-flash"),
        os.getenv("GEMINI_FALLBACK_MODEL", "gemini-3.8-flash-lite"),
    ]
    last_error: Exception | None = None
    for model in dict.fromkeys(models):
        for attempt in range(2):
            try:
                chat = client.chats.create(model=model, config=config)
                response = chat.send_message(question)
                if not response.text:
                    raise RuntimeError("Gemini returned an empty agent response")
                return response.text
            except errors.ServerError as error:
                last_error = error
                if attempt == 0:
                    time.sleep(2)
    raise RuntimeError(
        "Gemini models are temporarily unavailable after retries. "
        "Try again later or set GEMINI_MODEL to another available model."
    ) from last_error


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("question")
    parser.add_argument("--report", help="existing JSON report for the agent to read")
    parser.add_argument("--output", default="agent_insight.json")
    args = parser.parse_args()

    output_path = _safe_workspace_path(args.output)
    try:
        insight = ask_agent(args.question, report_path=args.report)
    except RuntimeError as error:
        insight = json.dumps(
            {
                "status": "error",
                "error": str(error),
                "action": "Retry the command later or configure GEMINI_MODEL.",
            },
            indent=2,
        )

    with output_path.open("w", encoding="utf-8") as output_file:
        output_file.write(insight)
    print(f"Saved agent insight to {args.output}")


if __name__ == "__main__":
    main()